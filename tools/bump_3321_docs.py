def patch(path, old, new, must=1):
    src = io.open(path, encoding='utf-8').read()
    n = src.count(old)
    if n != must:
        sys.exit('[docs] %s 锚点命中 %d 次（期望 %d）：%r' % (path, n, must, old[:60]))
    io.open(path, 'w', encoding='utf-8').write(src.replace(old, new, 1))
    print('[docs] ok %s' % path)


